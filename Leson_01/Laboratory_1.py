# 1. Задаем переменные (здесь указаны значения для Варианта 1)
# Поменяйте их на значения вашего варианта!
a = 12
b = 8
c = 5
d = 5
e = 10

print(f"Исходные данные: a={a}, b={b}, c={c}, d={d}, e={e}\n")

# 2. Умножьте переменную a на b и выведите результат в консоль.
step1 = a * b
print(f"1) Умножение a на b ({a} * {b}): {step1}")

# 3. Разделите полученный результат на c и выведите результат в консоль.
step2 = step1 / c
print(f"2) Деление результата на c ({step1} / {c}): {step2}")

# 4. Найдите 20 процентов от полученного значения и выведите результат в консоль.
step3 = step2 * 0.20
print(f"3) 20 процентов от значения ({step2} * 0.20): {step3}")

# 5. Прибавьте к нему переменную d и выведите результат в консоль.
step4 = step3 + d
print(f"4) Прибавление переменной d ({step3} + {d}): {step4}")

# 6. Сравните полученное значение с переменной e и выведите результат сравнения в консоль.
print(f"5) Сравнение полученного значения ({step4}) с переменной e ({e}):")

if step4 > e:
    print(f"   Результат: {step4} больше, чем {e}")
elif step4 < e:
    print(f"   Результат: {step4} меньше, чем {e}")
else:
    print(f"   Результат: {step4} равно {e}")